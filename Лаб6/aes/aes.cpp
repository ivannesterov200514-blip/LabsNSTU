void printstate(const uint8_t block[16], const string& label) {
	cout << label << ":\n";
	for (int r = 0; r < 4; ++r) {
		for (int c = 0; c < 4; ++c) {
			cout << hex << setw(2) << setfill('0') << (int)block[r + 4 * c] << " ";
		}
		cout << "\n";
	}
	cout << dec;
}

void printroundkeys(const uint8_t roundkeys[11][16]) {
	for (int r = 0; r <= 10; ++r) {
		string label = "Round key " + to_string(r);
		printstate(roundkeys[r], label);
		cout << "\n";
	}
}

void generate_key(uint8_t key[16]) {
	random_device rd;
	mt19937 gen(rd());
	uniform_int_distribution<int> dis(0, 255);
	for (int i = 0; i < 16; ++i)
		key[i] = static_cast<uint8_t>(dis(gen));

	const string filename = "aeskey.bin";
	ofstream file(filename, ios::binary | ios::trunc);
	if (!file) {
		cerr << "Ошибка: не удалось создать файл " << filename << "\n";
		throw runtime_error("Key file creation failed");
	}
	file.write(reinterpret_cast<const char*>(key), 16);
	file.close();
}

bool load_key(uint8_t key[16]) {
	const string filename = "aeskey.bin";
	ifstream file(filename, ios::binary);
	if (!file) return false;
	file.read(reinterpret_cast<char*>(key), 16);
	return file.good() && file.gcount() == 16;
}

void generate_iv(uint8_t iv[16]) {
	random_device rd;
	mt19937 gen(rd());
	uniform_int_distribution<int> dis(0, 255);
	for (int i = 0; i < 16; ++i)
		iv[i] = static_cast<uint8_t>(dis(gen));
}

void keyexpansion(const uint8_t key[16], uint8_t roundkeys[11][16]) {
	for (int i = 0; i < 16; ++i) roundkeys[0][i] = key[i];
	const uint8_t Rcon[10] = { 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36 };

	for (int r = 1; r <= 10; ++r) {
		for (int i = 0; i < 16; ++i)
			roundkeys[r][i] = roundkeys[r - 1][i];

		uint8_t temp[4] = {	roundkeys[r - 1][13], roundkeys[r - 1][14],	roundkeys[r - 1][15], roundkeys[r - 1][12] };

		for (int j = 0; j < 4; ++j) {
			temp[j] = S_box[temp[j]];
		}
		temp[0] ^= Rcon[r - 1];

		for (int j = 0; j < 4; ++j)
			roundkeys[r][j] ^= temp[j];

		for (int i = 4; i < 16; ++i)
			roundkeys[r][i] ^= roundkeys[r][i - 4];
	}
}

vector<uint8_t> pkcs7pad(const string& text) {
	vector<uint8_t> data(text.begin(), text.end());
	uint8_t pad = 16 - (data.size() % 16);
	data.insert(data.end(), pad, pad);
	return data;
}

string pkcs7unpad(const vector<uint8_t>& data) {
	uint8_t k = data.back();
	if (k < 1 || k > 16) {
		throw invalid_argument("Неверное значение PKCS7 паддинга");
	}

	for (size_t i = 0; i < k; ++i) {
		if (data[data.size() - 1 - i] != k) {
			throw invalid_argument("Проверка PKCS7 паддинга не пройдена");
		}
	}
	return string(data.begin(), data.end() - k);
}

void addroundkey(uint8_t block[16], const uint8_t round_key[16]) {
	for (int i = 0; i < 16; ++i) {
		block[i] ^= round_key[i];
	}
}

void subbytes(uint8_t block[16]) {
	for (int i = 0; i < 16; ++i) {
		block[i] = S_box[block[i]];
	}
}

void invsubbytes(uint8_t block[16]) {
	for (int i = 0; i < 16; ++i) {
		block[i] = Inv_S_box[block[i]];
	}
}

void shiftrows(uint8_t block[16]) {
	for (int r = 1; r < 4; ++r) {
		uint8_t temp[4];
		for (int i = 0; i < 4; ++i) {
			temp[i] = block[r + 4 * i];
		}
		for (int i = 0; i < 4; ++i) {
			block[r + 4 * i] = temp[(i + r) % 4];
		}
	}
}

void invshiftrows(uint8_t block[16]) {
	for (int r = 1; r < 4; ++r) {
		uint8_t temp[4];
		for (int i = 0; i < 4; ++i)
			temp[i] = block[r + 4 * i];

		for (int i = 0; i < 4; ++i)
			block[r + 4 * i] = temp[(4 + i - r) % 4];
	}
}

uint8_t xtime(uint8_t x) {
	return (x & 0x80) ? ((x << 1) ^ 0x1B) : (x << 1);
}

void mixcolumns(uint8_t block[16]) {
	auto mul2 = [](uint8_t x) { return xtime(x); };
	auto mul3 = [](uint8_t x) { return xtime(x) ^ x; };

	for (int col = 0; col < 4; ++col) {
		int i = col * 4;
		uint8_t a = block[i];
		uint8_t b = block[i + 1];
		uint8_t c = block[i + 2];
		uint8_t d = block[i + 3];

		block[i] = mul2(a) ^ mul3(b) ^ c ^ d;
		block[i + 1] = a ^ mul2(b) ^ mul3(c) ^ d;
		block[i + 2] = a ^ b ^ mul2(c) ^ mul3(d);
		block[i + 3] = mul3(a) ^ b ^ c ^ mul2(d);
	}
}

void invmixcolumns(uint8_t block[16]) {
	auto mul2 = [](uint8_t x) { return xtime(x); };
	auto mul9 = [&](uint8_t x) { return mul2(mul2(mul2(x))) ^ x; };
	auto mul11 = [&](uint8_t x) { return mul2(mul2(mul2(x))) ^ mul2(x) ^ x; };
	auto mul13 = [&](uint8_t x) { return mul2(mul2(mul2(x))) ^ mul2(mul2(x)) ^ x; };
	auto mul14 = [&](uint8_t x) { return mul2(mul2(mul2(x))) ^ mul2(mul2(x)) ^ mul2(x); };

	for (int col = 0; col < 4; ++col) {
		int i = col * 4;
		uint8_t a = block[i], b = block[i + 1], c = block[i + 2], d = block[i + 3];

		block[i] = mul14(a) ^ mul11(b) ^ mul13(c) ^ mul9(d);
		block[i + 1] = mul9(a) ^ mul14(b) ^ mul11(c) ^ mul13(d);
		block[i + 2] = mul13(a) ^ mul9(b) ^ mul14(c) ^ mul11(d);
		block[i + 3] = mul11(a) ^ mul13(b) ^ mul9(c) ^ mul14(d);
	}
}

void cryptblock(uint8_t block[16], const uint8_t roundkeys[11][16]) {
	addroundkey(block, roundkeys[0]);
	printstate(block, "State after rkey0");

	for (int r = 1; r < 10; ++r) {
		subbytes(block); 
		printstate(block, "State after subbytes(" + to_string(r) + ")");
		shiftrows(block); 
		printstate(block, "State after shiftrows(" + to_string(r) + ")");
		mixcolumns(block); 
		printstate(block, "State after mixcolumns(" + to_string(r) + ")");
		addroundkey(block, roundkeys[r]); 
		printstate(block, "State after rkey" + to_string(r) + ": ");
	}
	subbytes(block); 
	printstate(block, "State after subbytes(10)");
	shiftrows(block); 
	printstate(block, "State after shiftrows(10)");
	addroundkey(block, roundkeys[10]); 
	printstate(block, "State after rkey10");
}

void decryptblock(uint8_t block[16], const uint8_t roundkeys[11][16]) {
	addroundkey(block, roundkeys[10]);
	printstate(block, "State after AddRoundKey(10)");

	for (int r = 9; r >= 1; --r) {
		invshiftrows(block);
		printstate(block, "InvShiftRows(" + to_string(r) + ")");
		invsubbytes(block);
		printstate(block, "InvSubBytes(" + to_string(r) + ")");
		addroundkey(block, roundkeys[r]);
		printstate(block, "AddRoundKey(" + to_string(r) + ")");
		invmixcolumns(block);
		printstate(block, "InvMixColumns(" + to_string(r) + ")");
	}

	invshiftrows(block);
	printstate(block, "InvShiftRows(0)");
	invsubbytes(block);
	printstate(block, "InvSubBytes(0)");
	addroundkey(block, roundkeys[0]);
	printstate(block, "AddRoundKey(0)");
}

void cbcencrypt(const uint8_t roundkeys[11][16], const uint8_t iv[16], const vector<uint8_t>& data, vector<uint8_t>& cipher) {
	cipher.resize(data.size());
	uint8_t prev[16];
	for (int i = 0; i < 16; ++i)
		prev[i] = iv[i];
	uint8_t block[16];
	for (size_t i = 0; i < data.size(); i += 16) {
		uint8_t block[16];

		for (int j = 0; j < 16; ++j)
			block[j] = data[i + j];

		for (int j = 0; j < 16; ++j)
			block[j] ^= prev[j];
		cryptblock(block, roundkeys);

		for (int j = 0; j < 16; ++j) 
			cipher[i + j] = block[j];

		for (int j = 0; j < 16; ++j)
			prev[j] = block[j];
	}
}

void cbcdecrypt(const uint8_t roundkeys[11][16], const uint8_t iv[16], const vector<uint8_t>& cipher, vector<uint8_t>& data) {
	data.resize(cipher.size());
	uint8_t prev[16];
	for (int i = 0; i < 16; ++i) 
		prev[i] = iv[i];

	for (size_t i = 0; i < cipher.size(); i += 16) {
		uint8_t block[16];
		
		for (int j = 0; j < 16; ++j)
			block[j] = cipher[i + j];

		decryptblock(block, roundkeys);

		for (int j = 0; j < 16; ++j)
			block[j] ^= prev[j];

		for (int j = 0; j < 16; ++j)
			data[i + j] = block[j];

		for (int j = 0; j < 16; ++j)
			prev[j] = cipher[i + j];
	}
}